"""Write web/data.js from ak820/keys.py so the web app and the Python package share one source.

    python tools/gen_web_data.py          # regenerate
    python tools/gen_web_data.py --check  # exit 1 if web/data.js is stale (CI)
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from ak820 import __version__, keys, patterns  # noqa: E402

OUT = ROOT / "web" / "data.js"


def render() -> str:
    data = {
        "version": __version__,
        "keys": [{"code": c, "label": l, "led": led, "row": r, "col": col,
                  "rect": keys.KEY_RECTS[led]} for c, l, led, r, col in keys.PHYSICAL_KEYS],
        "modes": [{"mode": m, "name": n, "attr": a, "slug": keys.SLUG_BY_MODE.get(m)}
                  for m, (n, a) in keys.LIGHT_MODES.items()],
        "palette": [{"name": n, "rgb": rgb} for n, rgb in keys.PALETTE],
        "hid": keys.HID_USAGES,
        "media": keys.MEDIA_CODES,
        "aliases": keys.ALIASES,
        "fnCode": keys.FN_CODE,
        "powerStates": {str(k): v for k, v in keys.POWER_STATES.items()},
        "patterns": patterns.PATTERNS,
        "attr": {"brightness": keys.ATTR_BRIGHTNESS, "speed": keys.ATTR_SPEED,
                 "direction": keys.ATTR_DIRECTION, "color": keys.ATTR_COLOR},
        "customMode": keys.CUSTOM_MODE, "musicMode": keys.MUSIC_MODE,
        "rainbow": keys.RAINBOW,
    }
    return ("// generated by tools/gen_web_data.py from ak820/keys.py, don't edit by hand\n"
            f"export const DATA = {json.dumps(data, separators=(',', ':'))};\n")


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("web/data.js is out of date, run: python tools/gen_web_data.py")
        sys.exit(0)
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
